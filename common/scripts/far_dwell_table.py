#!/usr/bin/env python3
"""Tables for the dwell-time sensitivity analysis -> tables/t4_dwell_realised.tex
(requested t, K and realised dwell K/f per configuration) and
tables/t5_dwell_cox.tex (hazard ratios at 120/h, variant a, with the derived
false-alarm rate of edge-sim)."""
import sys
from pathlib import Path
import pandas as pd
sys.path.insert(0, str(Path(__file__).resolve().parent))
from far_dwell import F_MIN, MODES, OUT, k_of, realised_dwell_s  # noqa: E402
SC = OUT.parent / "paper/scirep"
CFGS = ["local-gpu", "remote-wifi", "remote-cellular-4g", "edge-sim"]
SHOW = ["fixed3", "t0.1", "t0.2", "t0.3", "t0.5", "t0.568", "t1", "t1.5"]
lab = lambda m: "$K=3$ frames" if m == "fixed3" else f"$t={MODES[m]:g}$ s"
cx = pd.read_csv(OUT / "phase2_far_dwell_cox.csv", index_col=0)
cx = cx[(cx.variant == "a") & (cx.target_far_h == 120.0)]
pl = pd.read_csv(OUT / "phase2_far_dwell_pooled.csv")
pl = pl[(pl.variant == "a") & (pl.target_far_h == 120.0)]
hdr = "% generated by common/scripts/far_dwell_table.py -- do not edit"

L = [hdr, r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
     r"Alarm rule & local-gpu, remote-lan & remote-wifi & remote-cellular-4g & edge-sim \\",
     r"\midrule"]
for m in SHOW:
    cells = [f"{k_of(m, c)} / {realised_dwell_s(m, c):.2f}" for c in CFGS]
    mark = r"$^\dagger$" if m != "fixed3" and MODES[m] < round(1 / F_MIN, 3) else ""
    L.append(f"{lab(m)}{mark} & " + " & ".join(cells) + r" \\")
L += [r"\bottomrule", r"\end{tabular}"]
(SC / "tables/t4_dwell_realised.tex").write_text("\n".join(L) + "\n")

def p(x): return "<0.0001" if x < 1e-4 else f"{x:.4f}"
cols = ["remote-lan", "remote-wifi", "remote-cellular-4g", "edge-sim"]
L = [hdr, r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
     r"Alarm rule & remote-lan & remote-wifi & remote-cellular-4g & edge-sim & edge-sim FAR (/h) \\",
     r"\midrule"]
for m in SHOW:
    g = cx[cx["mode"] == m]
    r = {c: g.loc["config_label_" + c] for c in cols}
    far = pl[(pl["mode"] == m) & (pl.config == "edge-sim")]["mean_derived_far_h"].iloc[0]
    mark = r"$^\dagger$" if m != "fixed3" and MODES[m] < round(1 / F_MIN, 3) else ""
    L.append(f"{lab(m)}{mark} & " + " & ".join(f"{r[c].HR:.2f}" for c in cols)
             + f" & {far:.0f}" + r" \\")
    L.append(r"\quad 95\% CI & " + " & ".join(f"{r[c].CI_lo:.2f}--{r[c].CI_hi:.2f}" for c in cols) + r" & \\")
    L.append(r"\quad $P$ & " + " & ".join(p(r[c].p) for c in cols) + r" & \\")
L += [r"\bottomrule", r"\end{tabular}"]
(SC / "tables/t5_dwell_cox.tex").write_text("\n".join(L) + "\n")
print("ok")

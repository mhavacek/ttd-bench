#!/usr/bin/env python3
"""Tables of the Scientific Reports version that are built from stored results.

Every value is read from a stored CSV, never typed: the fixed-threshold Cox
model with exact P values (results/scirep-stats, scirep_stats.py), the
onset-shift refits (results/onset-sensitivity), the calibrated hit rates and
hazard ratios (results-far-calib) and the equivalence tests of the repair
probe (results/rerun-eval). The script stops if a value the IEEE version
already quotes does not come out the same.

  scirep_tables.py   -> clanek-2-ttdbench/paper/scirep/tables/*.tex
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent.parent
P2 = ROOT / "clanek-2-ttdbench"
OUT = P2 / "paper/scirep/tables"
CONFIGS = ["remote-lan", "remote-wifi", "remote-cellular-4g", "edge-sim"]
MODELS = {"yolov8s-weapon": "YOLOv8s", "yolov8m-weapon": "YOLOv8m",
          "yolov12m-weapon": "YOLOv12m", "yolov26m-weapon": "YOLO26m"}
HEADER = "% generated by common/scripts/scirep_tables.py -- do not edit\n"


def pval(p: float) -> str:
    """P as Scientific Reports asks for it: exact, two significant digits."""
    if p >= 0.001:
        return f"{p:.2g}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def t1_cox() -> str:
    cox = pd.read_csv(ROOT / "results/scirep-stats/cox_exact.csv", index_col=0)
    sh = pd.read_csv(ROOT / "results/onset-sensitivity/cox_by_shift.csv")
    shifts = ["primary_earlier(-25f)", "primary_later(+25f)",
              "stress_earlier(-38f)", "stress_later(+38f)"]
    base = sh[sh["shift"] == "baseline"].set_index("config")
    for c in CONFIGS:  # the refits start from the published model
        assert abs(base.loc[c, "HR"] - cox.loc[f"config_label_{c}", "HR"]) < 5e-5, c
    rows = []
    rows.append(r"\multicolumn{8}{@{}l}{\itshape Deployment configuration "
                r"(reference local-gpu)}\\")
    for c in CONFIGS:
        r = cox.loc[f"config_label_{c}"]
        cells = [f"{sh[(sh['shift'] == s) & (sh['config'] == c)]['HR'].iloc[0]:.4f}"
                 for s in shifts]
        rows.append(f"{c} & {r.HR:.4f} & {r.CI_lo:.4f}--{r.CI_hi:.4f} & {pval(r.p)} & "
                    + " & ".join(cells) + r" \\")
    rows.append(r"\addlinespace")
    rows.append(r"\multicolumn{8}{@{}l}{\itshape Detector (reference YOLOv8s)}\\")
    for m in ["yolov8m-weapon", "yolov12m-weapon", "yolov26m-weapon"]:
        r = cox.loc[f"model_{m}"]
        rows.append(f"{MODELS[m]} & {r.HR:.4f} & {r.CI_lo:.4f}--{r.CI_hi:.4f} & "
                    f"{pval(r.p)} & \\multicolumn{{4}}{{c}}{{not part of the rule}} \\\\")
    return (HEADER + r"\begin{tabular}{@{}lrlrrrrr@{}}" + "\n\\toprule\n"
            r" & & & & \multicolumn{4}{c}{HR, onsets shifted by (frames)} \\" + "\n"
            r"\cmidrule(l){5-8}" + "\n"
            r"Term & HR & 95\% CI & $P$ & $-25$ & $+25$ & $-38$ & $+38$ \\" + "\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def t2_hit() -> str:
    s = pd.read_csv(P2 / "results-far-calib/phase2_far_summary.csv")
    s = s[s["config"] == "local-gpu"]
    curves = pd.read_parquet(P2 / "results-far-calib/far_curves.parquet")
    c05 = curves[(curves["config"] == "local-gpu") & (curves["threshold"].round(3) == 0.5)
                 ].set_index("model")["far_h"]
    # D11: yolov8s is scored at its deployed 416 px on local-gpu (1247.7/h at 640 px)
    assert round(c05["yolov8s-weapon"], 1) == 817.1 and round(c05["yolov26m-weapon"], 1) == 187.4
    fixed = s[s["operating_point"] == "old_conf0.5"].set_index("model")["hit_pct"]
    assert fixed["yolov8s-weapon"] == 73.5
    # chance level: hit rate that false alarms alone would produce (far_chance.py)
    ch = pd.read_csv(P2 / "results-far-calib/chance_level.csv")
    ch = ch[ch["config"] == "local-gpu"]
    chf = ch[ch["operating_point"] == "old_conf0.5"].set_index("model")["chance_hit_pct"]
    rows = ["Fixed confidence 0.5 & " + " & ".join(
        f"{fixed[m]:.1f} [{chf[m]:.1f}] ({c05[m]:.1f}/h)" for m in MODELS) + r" \\", r"\midrule"]
    a = s[s["variant"] == "a"]
    cha = ch[ch["variant"] == "a"]
    for t in ["0.1", "0.3", "1", "3", "12", "30", "60", "120", "300", "600"]:
        d = a[a["operating_point"] == f"far{t}"].set_index("model")["hit_pct"]
        c = cha[cha["operating_point"] == f"far{t}"].set_index("model")["chance_hit_pct"]
        cells = [f"{d[m]:.1f} [{c[m]:.1f}]" for m in MODELS]
        if t == "1":
            rows.append(r"\textbf{1} & " + " & ".join(rf"\textbf{{{v}}}" for v in cells) + r" \\")
        else:
            rows.append(f"{t} & " + " & ".join(cells) + r" \\")
    return (HEADER + r"\begin{tabular}{@{}lrrrr@{}}" + "\n\\toprule\n"
            r"Operating point & " + " & ".join(MODELS.values()) + r" \\" + "\n"
            r"(false alarms per camera-hour) & \multicolumn{4}{c}{Hit rate [chance level] (\%)} \\"
            + "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def t3_cox_calibrated() -> str:
    c = pd.read_csv(P2 / "results-far-calib/phase2_far_cox.csv")
    c = c[c["Unnamed: 0"].str.startswith("config_label_")].copy()
    c["config"] = c["Unnamed: 0"].str.replace("config_label_", "")
    ops = [("a", "far60", "60"), ("a", "far120", "120"), ("a", "far300", "300"),
           ("a", "far600", "600"), ("b", "far120", "120")]
    rows = []
    for i, (var, op, lab) in enumerate(ops):
        if i:
            rows.append(r"\midrule" if var == "b" else r"\addlinespace")
        d = c[(c["variant"] == var) & (c["operating_point"] == op)].set_index("config")
        hr = " & ".join(f"{d.loc[k, 'HR']:.4f}" for k in CONFIGS)
        ci = " & ".join(f"({d.loc[k, 'CI_lo']:.4f}--{d.loc[k, 'CI_hi']:.4f})" for k in CONFIGS)
        # stored P is rounded to four decimals, so 0.0 means P < 0.0001
        pv = " & ".join(r"$P<0.0001$" if d.loc[k, "p"] == 0 else f"$P={d.loc[k, 'p']:.4f}$"
                        for k in CONFIGS)
        n = int(d["n_events"].iloc[0])
        rows.append(f"({var}) {lab}/h, {n} events & {hr} \\\\")
        rows.append(r"\quad 95\% CI & " + ci + r" \\")
        rows.append(r"\quad & " + pv + r" \\")
    return (HEADER + r"\begin{tabular}{@{}lrrrr@{}}" + "\n\\toprule\n"
            r"Operating point & " + " & ".join(CONFIGS) + r" \\" + "\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def s_km() -> str:
    t = pd.read_csv(ROOT / "results/scirep-stats/km_ci.csv")
    med = pd.read_csv(P2 / "results-d10/analysis/km_table.csv", index_col=0)
    order = ["local-gpu", "remote-lan", "remote-wifi", "remote-cellular-4g", "edge-sim"]
    rows = []
    for cfg in order:
        d = t[t["config"] == cfg].set_index("t_ms")
        cells = [f"{d.loc[h, 'P_alarm']:.3f} ({d.loc[h, 'CI_lo']:.3f}--{d.loc[h, 'CI_hi']:.3f})"
                 for h in (500, 1000, 2000, 3000)]
        m = med.loc[cfg, "KM median TTD"]
        ms = "not reached" if math.isinf(m) else f"{m:.1f} ms"
        rows.append(f"{cfg} & {int(d['n'].iloc[0])} & {int(d['events'].iloc[0])} & "
                    + " & ".join(cells) + f" & {ms} \\\\")
    return (HEADER + r"\begin{tabular}{@{}lrrllllr@{}}" + "\n\\toprule\n"
            r"Configuration & $n$ & Events & $\le$0.5 s & $\le$1 s & $\le$2 s & $\le$3 s & "
            r"KM median \\" + "\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n")


def s_tost() -> str:
    s = pd.read_csv(ROOT / "results/rerun-eval/summary.csv")
    name = {"pf_latency_ms": "total per-frame latency", "pf_dt_infer_ms": "inference time"}
    lay = {"probe": "ten per job", "edgetest": "one per job",
           "probe+edgetest": "mixed$^{a}$"}
    s["order"] = s["layer"].map({"probe": 0, "edgetest": 1, "probe+edgetest": 2})
    s = s.sort_values(["order", "config"], key=lambda k: k if k.name == "order"
                      else k.map(lambda v: "~" if v == "POOLED" else v), kind="stable")
    rows = []
    for _, r in s.iterrows():
        if r["layer"] == "edgetest" and r["config"] == "POOLED":
            continue
        cfg = "pooled" if r["config"] == "POOLED" else r["config"]
        p = r"$<$0.0001" if r["tost_p"] < 0.0001 else f"{r['tost_p']:.4f}"
        rows.append(f"{cfg} & {lay[r['layer']]} & {name[r['metric']]} & {int(r['n'])} & "
                    f"${r['mean_z']:+.2f}$ & {p} & "
                    f"{'yes' if r['equivalent'] else 'no'} \\\\")
    return (HEADER + r"\begin{tabular}{@{}lllrrrl@{}}" + "\n\\toprule\n"
            r"Configuration & Packing & Metric & $n$ & Mean $z$ & TOST $P$ & Equivalent \\"
            + "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in [("t1_cox", t1_cox), ("t2_hit_calibrated", t2_hit),
                     ("t3_cox_calibrated", t3_cox_calibrated), ("s_km_ci", s_km),
                     ("s_tost", s_tost)]:
        (OUT / f"{name}.tex").write_text(fn())
    print(f"wrote {sorted(p.name for p in OUT.glob('*.tex'))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
